"""The demo's shaders and spike table must be the plugin's, character for character.

    python3 demo/tools/check_shaders.py           compare; exit 1 on any drift
    python3 demo/tools/check_shaders.py --write   regenerate demo/shaders.js and demo/spiketable.js

Called from `tools/verify.sh`. Exit code 1 means a copy has drifted.

------------------------------------------------------------------- why

The page runs two things copied out of the plugin rather than ported: the GLSL
and the solved spikes.

`demo/shaders.js` holds the eleven GLSL pieces of `source/Shaders.cpp` (the
kCommon library, kQuadVertex, and the fft, evolve, force, pack, bounds, spikes,
deposit, combine and render bodies) plus kVersion. `demo/spiketable.js` holds
the part of `source/SpikeTable.cpp` (generated by tools/spikes/generate.py) that
the plugin uploads to the GPU: for each fluid its basis coefficients against
the field, the four basis kernels' transforms, and the pattern engine's own
equilibrium, plus every scalar of its `Table` row. That is two copies of each,
and copies drift -- quietly, because a pool drawn by a *plausible* shader or a
*plausible* table looks exactly like one drawn by the right one. `fetest`
drives the real plugin class and has never heard of this page, and
`tools/glslc.sh` and `tools/spikes/check.py` look only at the C++ copies.

------------------------------------------------------------------- what it does

Shaders: pulls each `R"( ... )"` body out of `source/Shaders.cpp` and the
matching backtick literal out of `demo/shaders.js`, and compares them exactly
-- no whitespace normalisation, no comment stripping: a comment updated on one
side only is exactly the drift worth catching. `kVersion`, a plain string, is
compared too. The page does not change the version line: the kit's `port()`
does that at compile time, as it does for every demo in the fleet (the version
line and the ES precision defaults, nothing else).

It also fails when Shaders.cpp grows a piece this script does not list (a new
pass the page would silently lack), and it checks the JOIN as well as the
pieces: `Assemble()` in Shaders.cpp is kVersion + kCommon + the pass, and
InitGL in Ferrofluid.cpp builds the vertex stage as kVersion + kQuadVertex and
compiles nine fragment stages; plugin.js must assemble them the same way. A
change to either side's assembly fails here and needs a reader.

A piece may be several adjacent raw strings (MSVC refuses one literal over
about 16 KB, as slipstream's kSceneFragment found); they are joined as the
compiler joins them. None of this plugin's is today. The one transformation is
a decode: a backtick cannot appear raw in a template literal, so --write would
escape one as \\`. There are none in the C++ today, and any other backslash or
`${` on the JS side is rejected.

Table: every array the plugin uploads (kEq*, kCoef*, kBasis*) is compared
literal for literal, as text, with only the C++ `f` suffix dropped; every
scalar of each `kTables` row is compared as text, against the row's fields in
SpikeTable.h's order, so a reordered or added field fails; and the inputs hash
is compared. Every literal is also checked, exactly, in rationals, to become
the same float both ways: the page parses it to a double and Float32Array
rounds that to a float, where clang rounds it straight to a float, and the two
can differ when the double lands on a midpoint between floats that the decimal
itself is not on. They are 10-digit prints of doubles (generate.py's %.9e), so
that is rare but not impossible, and the check says which if it ever happens.

`--write` produces both files from the C++ by exactly those transformations,
so the copies are spliced by this script and never typed.

------------------------------------------------------------------- what it cannot

Nothing here checks the PORTED half. Controls.cpp (the mappings), Fluid.cpp
(the Langevin magnetisation, the demagnetising jump, the critical field, the
optics), Coil.cpp (the loop's field by the AGM, the solenoid's Gauss-Legendre
sum, the L/R lag), Drive.cpp (the beat, the pulses, the current), Spikes.cpp's
TableFor, and the frame logic of Ferrofluid.cpp (the tables, the critical
current, the substep plan, every uniform, the camera and the soft boxes) are a
hand translation in demo/plugin.js, and only a reader checks them. The page
says so. When you change one of those, change the port too.
"""
