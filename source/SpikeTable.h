#pragma once

/**
    The solved spikes: the shipped table, generated by tools/spikes/generate.py
    (SpikeTable.cpp; do not edit it, regenerate it).

    For each fluid preset, the equilibrium free surface of the hexagonal
    pattern's cell, solved offline with the full nonlinear magnetostatics (the
    Langevin curve inside the fluid, vacuum outside, gravity and the full
    capillary curvature: Gollwitzer et al., J. Fluid Mech. 571, 2007's
    problem), along its branch from the flat surface's bifurcation, round the
    fold, up the stable branch to the end of the drive's range or of what the
    solver resolves.

    The stable branch is sampled on a grid uniform in v = sqrt( u - u_fold ),
    u = Ha / Ha_c the applied field over the onset's (in a uniform field, the
    plugin's I / I_c). Each sample is an isotropic kernel s( r ), given by its
    Fourier transform s^( q ), q = k / k_c, as kBasis coefficients on a shared
    basis: s^( q; v ) = sum_j coef[ v ][ j ] basis[ q ][ j ]. A lattice of such
    kernels sums to exactly the solved cell (the kernel's transform equals
    the cell's area times its Fourier amplitude at every reciprocal lattice
    vector up to sqrt 67 k_c = 8.19 k_c, and zero at every one from the next,
    sqrt 73 k_c = qMax, on); between those shells the kernel is a smooth
    spline, which only a spike without its six neighbours sees.
*/
namespace ferrofluid::spikes
{
constexpr int kBasis = 4;

struct Table
{
	const char* fluid;
	double uFold;      ///< the fold: the stable branch's lowest field, u
	double mFold;      ///< the same as a magnetic number
	double peakAtOnset;///< the stable branch's peak height at u = 1, m
	double vEnd;       ///< the grid's last v = sqrt( u - u_fold )
	double uEnd;       ///< and its u
	int nGrid;
	const float* coefficients;///< nGrid x kBasis
	const float* peak;        ///< nGrid: the cell's peak height, m (its mean is 0)
	const float* amplitude;   ///< nGrid: peak minus the cell's corners (Gollwitzer et al.'s amplitude), m
	const float* tipRadius;   ///< nGrid: the tip's radius of curvature, m
	int nQ;
	double qMax;             ///< the basis spans q in [ 0, qMax ], k_c units
	const float* basis;      ///< nQ x kBasis, m^3
	int nBranch;             ///< the whole branch as solved, unstable part included
	const float* branchU;
	const float* branchPeak;
	/// The pattern engine's two constants, fitted to this fluid's solved branch
	/// (its fold, and its peak at onset in k_c units) by `fetest --calibrate`.
	double hysteresis, saturation;
	/// The pattern engine's own equilibrium peak height against u, for the
	/// blend: nEq samples over [ eqU0, eqU1 ], metres; below its fold, the
	/// fold's (the smallest spike it holds).
	int nEq;
	double eqU0, eqU1;
	const float* eqPeak;
};

/// The table for a preset, by its index in Controls' fluid list (EFH1, EMG 901, EMG 909).
const Table& TableFor( int fluidIndex );
/// The SHA-256 of the generator's sources, as SpikeTable.cpp was made from them.
extern const char* const kInputsHash;
extern const Table kTables[];
constexpr int kTableCount = 3;

/// The kernel's transform at q for the grid's fractional index (linear in both), m^3.
double KernelHat( const Table& t, double index, double q );
/// The grid position (fractional index) for u; clamped to [ 0, nGrid - 1 ].
double GridIndex( const Table& t, double u );
} // namespace ferrofluid::spikes
